// Events and observers
// ---------------------------------------------------------------------------

// Event is a model lifecycle event.
type Event int

const (
	Retrieved Event = iota
	Creating
	Created
	Updating
	Updated
	Saving
	Saved
	Deleting
	Deleted
	Trashed
	ForceDeleting
	ForceDeleted
	Restoring
	Restored
	Replicating
)

// On registers a listener. Returning an error from a "-ing" listener aborts
// the operation (Eloquent's "return false").
func (t *Table[M]) On(e Event, fn func(ctx context.Context, m *M) error) {
	t.mu.Lock()
	defer t.mu.Unlock()
	if t.listeners == nil {
		t.listeners = map[Event][]func(context.Context, *M) error{}
	}
	t.listeners[e] = append(t.listeners[e], fn)
}

// Observe registers every lifecycle method obs implements, e.g.
//
//	func (UserObserver) Creating(ctx context.Context, u *User) error
func (t *Table[M]) Observe(obs any) {
	type h = func(context.Context, *M) error
	methods := map[Event]h{}
	if o, ok := obs.(interface {
		Retrieved(context.Context, *M) error
	}); ok {
		methods[Retrieved] = o.Retrieved
	}
	if o, ok := obs.(interface {
		Creating(context.Context, *M) error
	}); ok {
		methods[Creating] = o.Creating
	}
	if o, ok := obs.(interface {
		Created(context.Context, *M) error
	}); ok {
		methods[Created] = o.Created
	}
	if o, ok := obs.(interface {
		Updating(context.Context, *M) error
	}); ok {
		methods[Updating] = o.Updating
	}
	if o, ok := obs.(interface {
		Updated(context.Context, *M) error
	}); ok {
		methods[Updated] = o.Updated
	}
	if o, ok := obs.(interface {
		Saving(context.Context, *M) error
	}); ok {
		methods[Saving] = o.Saving
	}
	if o, ok := obs.(interface {
		Saved(context.Context, *M) error
	}); ok {
		methods[Saved] = o.Saved
	}
	if o, ok := obs.(interface {
		Deleting(context.Context, *M) error
	}); ok {
		methods[Deleting] = o.Deleting
	}
	if o, ok := obs.(interface {
		Deleted(context.Context, *M) error
	}); ok {
		methods[Deleted] = o.Deleted
	}
	if o, ok := obs.(interface {
		Trashed(context.Context, *M) error
	}); ok {
		methods[Trashed] = o.Trashed
	}
	if o, ok := obs.(interface {
		ForceDeleting(context.Context, *M) error
	}); ok {
		methods[ForceDeleting] = o.ForceDeleting
	}
	if o, ok := obs.(interface {
		ForceDeleted(context.Context, *M) error
	}); ok {
		methods[ForceDeleted] = o.ForceDeleted
	}
	if o, ok := obs.(interface {
		Restoring(context.Context, *M) error
	}); ok {
		methods[Restoring] = o.Restoring
	}
	if o, ok := obs.(interface {
		Restored(context.Context, *M) error
	}); ok {
		methods[Restored] = o.Restored
	}
	if o, ok := obs.(interface {
		Replicating(context.Context, *M) error
	}); ok {
		methods[Replicating] = o.Replicating
	}
	if len(methods) == 0 {
		panic(fmt.Sprintf("orm: %T implements no observer methods for %s", obs, t.Name))
	}
	for e, fn := range methods {
		t.On(e, fn)
	}
}

type quietKey struct{}

// WithoutEvents returns a ctx in which no model events fire
// (saveQuietly, Model::withoutEvents).
func WithoutEvents(ctx context.Context) context.Context {
	return context.WithValue(ctx, quietKey{}, true)
}

func (t *Table[M]) fire(ctx context.Context, e Event, m *M) error {
	if ctx.Value(quietKey{}) != nil {
		return nil
	}
	t.mu.RLock()
	ls := t.listeners[e]
	t.mu.RUnlock()
	for _, fn := range ls {
		if err := fn(ctx, m); err != nil {
			return err
		}
	}
	return nil
}
