var (
	// ErrNotFound is returned when no row matches (firstOrFail, findOrFail).
	ErrNotFound = errors.New("orm: record not found")
	// ErrMultipleRecords is returned by Sole when more than one row matches.
	ErrMultipleRecords = errors.New("orm: multiple records found")
)

// KeyType is how a table's primary key is generated.
type KeyType int

const (
	KeyAutoIncrement KeyType = iota // database-assigned integer
	KeyUUID                         // UUIDv7 generated on create (HasUuids)
	KeyULID                         // ULID generated on create (HasUlids)
	KeyManual                       // caller sets it
)

// Table describes how model M maps to a table. Generated by ormgen from the
// //orm:table directive — the equivalent of Laravel 13's #[Table],
// #[Connection], #[WithoutTimestamps] and SoftDeletes configuration.
type Table[M any] struct {
	Name       string
	Connection string // empty: DefaultConnection
	PrimaryKey string // empty: no primary key (e.g. pivot tables)
	KeyType    KeyType
	CreatedAt  string // empty: not maintained
	UpdatedAt  string
	DeletedAt  string // non-empty enables soft deletes
	MorphAlias string // value stored in *_type columns; defaults to Name
	// TimePrecision is how many fractional second digits the maintained
	// timestamps keep, 0 (default) to 9; match the columns' precision.
	TimePrecision int
	Columns       []string
	// NullZero lists columns whose zero value is written as NULL
	// (db:"country_id,nullzero"), e.g. optional foreign keys.
	NullZero []string

	// Ptr returns a pointer to the field backing column (persisted or virtual).
	Ptr func(m *M, column string) any
	// State returns the embedded orm.Model.
	State func(m *M) *Model

	mu        sync.RWMutex
	scopes    []namedScope[M]
	listeners map[Event][]func(context.Context, *M) error
}

// TableRef is a model's table: its generated schema (Users) or the
// *Table itself (Users.Table). Builder methods that name a table take it,
// so completion offers the schemas instead of a table-name string.
type TableRef[M any] interface{ tableRef() *Table[M] }

func (t *Table[M]) tableRef() *Table[M] { return t }

// Model is embedded in every model struct. It tracks whether the row
// exists and what it looked like when loaded, for dirty checking.
type Model struct {
	exists          bool
	recentlyCreated bool
	original        map[string]any
	changes         []string
}

// Exists reports whether the model was loaded from or saved to the database.
func (m *Model) Exists() bool { return m.exists }

// WasRecentlyCreated reports whether the last save inserted the row.
func (m *Model) WasRecentlyCreated() bool { return m.recentlyCreated }

func (t *Table[M]) state(m *M) *Model { return t.State(m) }

func (t *Table[M]) connection() string { return cmp.Or(t.Connection, DefaultConnection) }

func (t *Table[M]) morphAlias() string { return cmp.Or(t.MorphAlias, t.Name) }

func (t *Table[M]) softDeletes() bool { return t.DeletedAt != "" }

// keyValues converts ids to the primary key's Go type. An integer of any
// width converts to an integer key when it fits, text to a text-kinded
// key; anything else is an error naming both types.
func (t *Table[M]) keyValues(ids []any) ([]any, error) {
	if t.PrimaryKey == "" {
		return nil, fmt.Errorf("orm: %s has no primary key to look up by", t.Name)
	}
	kt := reflect.TypeOf(t.Ptr(new(M), t.PrimaryKey)).Elem()
	out := make([]any, len(ids))
	for i, id := range ids {
		v, err := convertKey(id, kt)
		if err != nil {
			return nil, fmt.Errorf("orm: key %v for %s.%s: %w", id, t.Name, t.PrimaryKey, err)
		}
		out[i] = v
	}
	return out, nil
}

func convertKey(id any, kt reflect.Type) (any, error) {
	if id == nil {
		return nil, errors.New("a key cannot be nil")
	}
	v := reflect.ValueOf(id)
	switch {
	case v.Type() == kt:
		return id, nil
	case isIntegerKind(v.Kind()) && isIntegerKind(kt.Kind()):
		dst := reflect.New(kt).Elem()
		if err := assign(dst, id); err != nil {
			return nil, err
		}
		return dst.Interface(), nil
	case v.Kind() == reflect.String && kt.Kind() == reflect.String:
		return v.Convert(kt).Interface(), nil
	}
	return nil, fmt.Errorf("it is a %s, but the key is a %s", v.Type(), kt)
}

func isIntegerKind(k reflect.Kind) bool {
	switch k {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return true
	}
	return false
}

func (t *Table[M]) column(name string) Scalar[M, any] {
	return Scalar[M, any]{f: func(b *SQL) { b.Col(t.Name, name) }, tab: t.Name, col: name}
}

func (t *Table[M]) keyOrder() Order[M] {
	pk := tableColumn[M]{t, t.PrimaryKey}
	return Order[M]{f: func(b *SQL) { pk.build(b); b.Write(" ASC") }, e: pk, col: pk}
}

// value reads a column's current value from m.
func (t *Table[M]) value(m *M, col string) any {
	return reflect.ValueOf(t.Ptr(m, col)).Elem().Interface()
}

func (t *Table[M]) setValue(m *M, col string, v any) {
	dst := reflect.ValueOf(t.Ptr(m, col)).Elem()
	src := reflect.ValueOf(v)
	switch {
	case dst.Kind() == reflect.Pointer && src.Type() == dst.Type().Elem():
		p := reflect.New(src.Type())
		p.Elem().Set(src)
		dst.Set(p)
	case src.Type().ConvertibleTo(dst.Type()):
		dst.Set(src.Convert(dst.Type()))
	default:
		panic(fmt.Sprintf("orm: cannot assign %T to %s.%s (%s)", v, t.Name, col, dst.Type()))
	}
}

// dbValue is the value written for col: nil for zero nullzero columns
// and for zero times (which no database stores meaningfully).
func (t *Table[M]) dbValue(m *M, col string) any { return t.writeValue(col, t.value(m, col)) }

func (t *Table[M]) writeValue(col string, v any) any {
	if tm, ok := v.(time.Time); ok && tm.IsZero() {
		return nil
	}
	if slices.Contains(t.NullZero, col) && isZero(v) {
		return nil
	}
	return v
}

// key returns the primary key value of m.
func (t *Table[M]) key(m *M) any { return t.value(m, t.PrimaryKey) }

// sync marks m as persisted and snapshots its columns as the new original.
// The snapshot is a deep copy, so edits made in place (a slice element, a
// map entry, a pointee) still show as dirty.
func (t *Table[M]) sync(m *M) {
	st := t.state(m)
	st.exists = true
	st.original = make(map[string]any, len(t.Columns))
	for _, c := range t.Columns {
		st.original[c] = snapshot(t.value(m, c))
	}
}

func snapshot(v any) any {
	switch v.(type) {
	case nil, string, bool, int, int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64, float32, float64, time.Time:
		return v
	}
	return deepCopy(reflect.ValueOf(v)).Interface()
}

func deepCopy(v reflect.Value) reflect.Value {
	switch v.Kind() {
	case reflect.Pointer, reflect.Interface:
		if v.IsNil() {
			return v
		}
		if v.Kind() == reflect.Interface {
			c := reflect.New(v.Type()).Elem()
			c.Set(deepCopy(v.Elem()))
			return c
		}
		c := reflect.New(v.Type().Elem())
		c.Elem().Set(deepCopy(v.Elem()))
		return c
	case reflect.Slice:
		if v.IsNil() {
			return v
		}
		c := reflect.MakeSlice(v.Type(), v.Len(), v.Len())
		for i := range v.Len() {
			c.Index(i).Set(deepCopy(v.Index(i)))
		}
		return c
	case reflect.Map:
		if v.IsNil() {
			return v
		}
		c := reflect.MakeMapWithSize(v.Type(), v.Len())
		for it := v.MapRange(); it.Next(); {
			c.SetMapIndex(it.Key(), deepCopy(it.Value()))
		}
		return c
	case reflect.Array, reflect.Struct:
		c := reflect.New(v.Type()).Elem()
		c.Set(v)
		if v.Kind() == reflect.Array {
			for i := range v.Len() {
				c.Index(i).Set(deepCopy(v.Index(i)))
			}
			return c
		}
		for i := range v.NumField() {
			if c.Field(i).CanSet() {
				c.Field(i).Set(deepCopy(v.Field(i)))
			}
		}
		return c
	}
	return v
}

// Dirty returns the columns changed since m was loaded or saved (getDirty).
func (t *Table[M]) Dirty(m *M) []string {
	st := t.state(m)
	var dirty []string
	for _, c := range t.Columns {
		if orig, ok := st.original[c]; !ok || !equal(orig, t.value(m, c)) {
			dirty = append(dirty, c)
		}
	}
	return dirty
}

// IsDirty reports whether any column (or any of cols) changed.
func (t *Table[M]) IsDirty(m *M, cols ...AnyColumn[M]) bool {
	dirty := t.Dirty(m)
	if len(cols) == 0 {
		return len(dirty) > 0
	}
	return slices.ContainsFunc(cols, func(c AnyColumn[M]) bool { return slices.Contains(dirty, c.Name()) })
}

// IsClean is the inverse of IsDirty.
func (t *Table[M]) IsClean(m *M, cols ...AnyColumn[M]) bool { return !t.IsDirty(m, cols...) }

// WasChanged reports whether the last save changed any column (or any of cols).
func (t *Table[M]) WasChanged(m *M, cols ...AnyColumn[M]) bool {
	changes := t.state(m).changes
	if len(cols) == 0 {
		return len(changes) > 0
	}
	return slices.ContainsFunc(cols, func(c AnyColumn[M]) bool { return slices.Contains(changes, c.Name()) })
}

// IsNot is the inverse of Is.
func (t *Table[M]) IsNot(a, b *M) bool { return !t.Is(a, b) }

// Is reports whether a and b are the same row (same table, connection and key).
func (t *Table[M]) Is(a, b *M) bool {
	return t.PrimaryKey != "" && equal(t.key(a), t.key(b))
}

// ---------------------------------------------------------------------------
// Global scopes
// ---------------------------------------------------------------------------

type namedScope[M any] struct {
	name string
	fn   func(Query[M]) Query[M]
}

// softDeleteScope is the name of the built-in soft delete global scope.
const softDeleteScope = "softDeletes"

// AddGlobalScope registers a scope applied to every query on the table
// (including relation and whereHas subqueries) unless removed with
// WithoutGlobalScope.
func (t *Table[M]) AddGlobalScope(name string, fn func(Query[M]) Query[M]) {
	t.mu.Lock()
	defer t.mu.Unlock()
	t.scopes = append(t.scopes, namedScope[M]{name, fn})
}

func (t *Table[M]) globalScopes() []namedScope[M] {
	t.mu.RLock()
	defer t.mu.RUnlock()
	return slices.Clone(t.scopes)
}

